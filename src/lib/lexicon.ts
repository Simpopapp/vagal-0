/** Entradas indexadas pelo termo normalizado. */
export const LEXICON: Record<string, LexEntry> = (() => {
  const map: Record<string, LexEntry> = {};
  for (const raw of RAW) {
    const term = (raw.term ?? "").toLowerCase();
    map[term] = { ...raw, term } as LexEntry;
  }
  return map;
})();

/** Formas flexionadas simples: boats → boat, folding → fold, quietly → quiet. */
const SUFFIXES = ["s", "es", "ed", "ing", "ly", "er", "est", "'s", "’s"];

export function lookupWord(norm: string): LexEntry | undefined {
  if (!norm) return undefined;
  const direct = LEXICON[norm];
  if (direct) return direct;

  for (const suffix of SUFFIXES) {
    if (norm.endsWith(suffix) && norm.length > suffix.length + 2) {
      const base = norm.slice(0, -suffix.length);
      const hit = LEXICON[base];
      if (hit) return hit;
      if (LEXICON[`${base}e`]) return LEXICON[`${base}e`];
    }
  }

  // dobramento de consoante final: stopped → stop
  const doubled = norm.replace(/([bdfglmnprt])\1(ed|ing)$/, "$1");
  if (doubled !== norm) {
    const hit = LEXICON[doubled];
    if (hit) return hit;
  }

  return undefined;
}

/** Termo base para agrupar a mesma palavra em letras diferentes. */
export function lemmaOf(norm: string): string {
  return lookupWord(norm)?.term ?? norm;
}

export function categoryOf(norm: string): string {
  const entry = lookupWord(norm);
  if (!entry) return "sem curadoria";
  return entry.tags[0] ?? entry.pos;
}

/** Distratores do léxico para a prática quando o vocabulário é pequeno. */
export function lexiconLiterals(limit = 40): { term: string; literal: string }[] {
  return Object.values(LEXICON)
    .slice(0, limit)
    .map((entry) => ({ term: entry.term, literal: entry.literal }));
}
